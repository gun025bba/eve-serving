#!/bin/bash
# One-time (idempotent) PostgreSQL setup for conversation storage.
#   - localhost-only listener, peer auth on the unix socket, scram on 127.0.0.1/::1
#   - brew services (launchd) manages the server
#   - role "llmchat" (random password), databases llmchat + llmchat_test,
#     extensions pg_trgm + vector (pgvector, reserved for RAG)
#   - writes ~/llm-serving/.db_env (chmod 600, gitignored) with
#     GW_DATABASE_URL / GW_TEST_DATABASE_URL. The password is never printed.
# Requires: brew install postgresql@18 pgvector
set -euo pipefail
PG_FORMULA="${PG_FORMULA:-postgresql@18}"
BREW="$(command -v brew || echo /opt/homebrew/bin/brew)"
PREFIX="$("$BREW" --prefix)"
export PATH="$PREFIX/opt/$PG_FORMULA/bin:$PREFIX/bin:$PATH"
DATA="$PREFIX/var/$PG_FORMULA"
BASE="${BASE:-$HOME/llm-serving}"
ENVF="$BASE/.db_env"
PORT="${PGPORT:-5432}"

conf="$DATA/postgresql.conf"
if ! grep -q "^listen_addresses = 'localhost'" "$conf"; then
  printf "\n# llm-serving: loopback only\nlisten_addresses = 'localhost'\nport = %s\n" "$PORT" >> "$conf"
  echo "set listen_addresses='localhost' in $conf"
fi
hba="$DATA/pg_hba.conf"
if ! grep -q "llm-serving" "$hba"; then
  cp "$hba" "$hba.orig"
  cat > "$hba" <<HBA
# llm-serving: peer auth for the local OS superuser on the unix socket,
# passwords (scram-sha-256) for TCP, loopback only.
local   all             all                                     peer
host    all             all             127.0.0.1/32            scram-sha-256
host    all             all             ::1/128                 scram-sha-256
local   replication     all                                     peer
HBA
  echo "rewrote $hba (backup: $hba.orig)"
fi
"$BREW" services restart "$PG_FORMULA" >/dev/null
for _ in $(seq 30); do pg_isready -q -h 127.0.0.1 -p "$PORT" && break; sleep 1; done
pg_isready -h 127.0.0.1 -p "$PORT"

psql_su() { psql -X -q -v ON_ERROR_STOP=1 -p "$PORT" -d postgres "$@"; }
if [ ! -s "$ENVF" ]; then
  PW="$(openssl rand -hex 24)"
  umask 077
  cat > "$ENVF" <<ENV
# Local DB credentials for the gateway. NEVER commit. Generated by deploy/pg-setup.sh
GW_DATABASE_URL=postgres://llmchat:$PW@127.0.0.1:$PORT/llmchat?sslmode=disable
GW_TEST_DATABASE_URL=postgres://llmchat:$PW@127.0.0.1:$PORT/llmchat_test?sslmode=disable
ENV
  chmod 600 "$ENVF"
  echo "wrote $ENVF (600)"
fi
PW="$(sed -n 's#^GW_DATABASE_URL=postgres://llmchat:\([^@]*\)@.*#\1#p' "$ENVF")"
psql_su <<SQL
SELECT 'CREATE ROLE llmchat LOGIN' WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='llmchat')\gexec
ALTER ROLE llmchat WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$PW';
SELECT 'CREATE DATABASE llmchat OWNER llmchat' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname='llmchat')\gexec
SELECT 'CREATE DATABASE llmchat_test OWNER llmchat' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname='llmchat_test')\gexec
SQL
for db in llmchat llmchat_test; do
  psql -X -q -v ON_ERROR_STOP=1 -p "$PORT" -d "$db" -c "CREATE EXTENSION IF NOT EXISTS pg_trgm; CREATE EXTENSION IF NOT EXISTS vector;"
done
unset PW
echo "ok: role llmchat, databases llmchat/llmchat_test, extensions pg_trgm+vector"
